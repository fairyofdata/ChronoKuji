async def seed_dummy_data():
    async with AsyncSessionLocal() as db:
        print("🧹 기존 데이터를 초기화합니다...")
        await db.execute(delete(OmikujiHistory))
        await db.execute(delete(OmikujiMaster))
        await db.execute(delete(Spot))
        await db.commit()

        print("🌱 12대 세계관 및 맞춤형 오미쿠지 마스터 데이터 삽입을 시작합니다...")

        # 1. 스팟 데이터 삽입
        created_spots = {}
        for data in SPOT_DEFINITIONS:
            spot = Spot(
                id=data["id"],
                name=data["name"],
                theme_metadata={
                    "system_prompt": data["prompt"],
                    "bg_image": data["bg_image"],
                    "item_image": data["item_image"]
                }
            )
            db.add(spot)
            created_spots[data["id"]] = (spot, data["lucky"], data["item_image"])

        await db.commit()

        # 2. 각 세계관별 7대 등급 맞춤 오미쿠지 데이터 삽입
        omikujis = []
        directions = ["동쪽", "서쪽", "남쪽", "북쪽", "남동쪽", "북동쪽", "남서쪽", "북서쪽"]
        tiers = ["대길", "중길", "소길", "길", "말길", "흉", "대흉"]

        for spot_id, spot_data in WORLD_OMIKUJI_DATA.items():
            spot_info = created_spots.get(spot_id)
            if not spot_info:
                continue
            spot, lucky_item, item_image = spot_info
            await db.refresh(spot)

            for idx, tier_name in enumerate(tiers):
                tier_data = spot_data.get(tier_name)
                if not tier_data:
                    continue

                is_good = "길" in tier_name
                omikujis.append(
                    OmikujiMaster(
                        spot_id=spot.id,
                        luck_level=tier_name,
                        original_text=tier_data["text"],
                        meta_info={
                            "poem": tier_data["poem"],
                            "lucky_item": lucky_item if is_good else "주의와 경계",
                            "item_image": item_image,
                            "lucky_direction": f"{directions[idx % len(directions)]} 차원의 바람",
                            "lucky_number": (idx * 13 + spot.id * 7) % 99 + 1,
                            "categories": tier_data["categories"]
                        }
                    )
                )

        db.add_all(omikujis)
        await db.commit()
        
        print(f"🎉 12개 스팟 × 7대 정통 등급 = 총 {len(omikujis)}건의 세계관 맞춤 오미쿠지 마스터 데이터 생성 완료!")

if __name__ == "__main__":
    asyncio.run(seed_dummy_data())